import 'package:freezed_annotation/freezed_annotation.dart';

part 'app_config.freezed.dart';

/// Build flavor. Pass via `--dart-define=FLAVOR=staging`.
enum Flavor {
  dev,
  staging,
  prod;

  static Flavor fromName(String? name) =>
      Flavor.values.firstWhere((f) => f.name == name, orElse: () => Flavor.dev);
}

/// Immutable runtime configuration shared by every package.
///
/// Build it once in `main_<flavor>.dart` (or [AppConfig.fromEnvironment])
/// and inject it; never read `String.fromEnvironment` deep inside packages.
///
/// `==`, `hashCode`, `toString` and `copyWith` are generated by Freezed.
@freezed
final class AppConfig with _$AppConfig {
  const AppConfig({
    required this.flavor,
    required this.apiBaseUrl,
    this.appName = 'Vietlife',
    this.connectTimeout = const Duration(seconds: 15),
    this.receiveTimeout = const Duration(seconds: 30),
    bool? enableNetworkLogs,
    bool? enableAnalytics,
  }) : enableNetworkLogs = enableNetworkLogs ?? flavor != Flavor.prod,
       enableAnalytics = enableAnalytics ?? flavor == Flavor.prod;

  /// Reads `FLAVOR` and `API_BASE_URL` from `--dart-define`s.
  factory AppConfig.fromEnvironment() {
    const flavor = String.fromEnvironment('FLAVOR', defaultValue: 'dev');
    const baseUrl = String.fromEnvironment('API_BASE_URL');
    if (baseUrl.isEmpty) {
      throw StateError('Missing --dart-define=API_BASE_URL');
    }
    return AppConfig(flavor: Flavor.fromName(flavor), apiBaseUrl: baseUrl);
  }

  final Flavor flavor;
  final String apiBaseUrl;
  final String appName;
  final Duration connectTimeout;
  final Duration receiveTimeout;
  final bool enableNetworkLogs;
  final bool enableAnalytics;

  bool get isProd => flavor == Flavor.prod;
  bool get isDev => flavor == Flavor.dev;
}
